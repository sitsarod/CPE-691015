type SocialItem = {
  key: string;
  href: string;
  label: string;
  Icon: ComponentType<IconProps>;
  hover: string;
};

export default function SocialLinks({
  content,
  variant = "light",
  className = "",
}: {
  content: Pick<
    HomeContent,
    "facebook_url" | "instagram_url" | "tiktok_url" | "youtube_url" | "line_url"
  >;
  variant?: "light" | "dark";
  className?: string;
}) {
  const items: SocialItem[] = [
    { key: "facebook", href: content.facebook_url, label: "Facebook", Icon: FacebookIcon, hover: "hover:text-[#1877F2]" },
    { key: "instagram", href: content.instagram_url, label: "Instagram", Icon: InstagramIcon, hover: "hover:text-[#E4405F]" },
    { key: "tiktok", href: content.tiktok_url, label: "TikTok", Icon: TiktokIcon, hover: "hover:text-black" },
    { key: "youtube", href: content.youtube_url, label: "YouTube", Icon: YoutubeIcon, hover: "hover:text-[#FF0000]" },
    { key: "line", href: content.line_url, label: "LINE", Icon: LineIcon, hover: "hover:text-[#06C755]" },
  ].filter((item) => item.href && item.href.trim() !== "");

  if (items.length === 0) return null;

  const baseColor = variant === "dark" ? "text-gray-300" : "text-gray-500";

  return (
    <div className={`flex items-center gap-4 ${className}`}>
      {items.map(({ key, href, label, Icon, hover }) => (
        <a
          key={key}
          href={href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label}
          title={label}
          className={`${baseColor} ${hover} transition-colors`}
        >
          <Icon className="w-6 h-6" />
        </a>
      ))}
    </div>
  );
}
