// ตั้งเป็นระบบ "ไม่บังคับจนกว่าจะตั้งค่า" โดยตั้งใจ ถ้าทำกลับกัน (บังคับไว้ก่อน
// แล้วค่อยผ่อน) จะสร้างแอดมินคนแรกตอนติดตั้งใหม่ไม่ได้เลย เพราะยังไม่มีใคร
// เข้าไปตั้งค่าอะไรได้ — เป็นปัญหาไก่กับไข่ที่ไม่มีทางออกในระบบ
// ─────────────────────────────────────────────────────────────────────────────

var (
	ErrEmailInvalid     = errors.New("รูปแบบอีเมลไม่ถูกต้อง")
	ErrAdminEmailDomain = errors.New("บัญชีผู้ดูแลระบบต้องใช้อีเมลของโรงเรียนเท่านั้น")
)

// NormalizeEmail จัดรูปแบบอีเมลให้เทียบกันได้ (ตัดช่องว่าง + ตัวพิมพ์เล็ก)
//
// หมายเหตุ: ตั้งใจไม่ตัดจุดและไม่ตัดส่วน +tag ของ gmail ออก
// แม้ว่า a.b+x@gmail.com กับ ab@gmail.com จะเป็นบัญชีเดียวกันในสายตา Google
// (ซึ่งแปลว่าคนหนึ่งคนสมัครสมาชิกซ้ำได้หลายบัญชี) แต่ถ้าเปลี่ยนตอนนี้
// อีเมลที่เก็บไว้เดิมจะเทียบไม่ตรงกับที่ผู้ใช้พิมพ์ตอนล็อกอิน แล้วคนเดิมเข้าระบบไม่ได้
// ถ้าจะทำต้องเขียน migration แปลงข้อมูลเดิมพร้อมกัน — แยกเป็นงานต่างหาก
func NormalizeEmail(raw string) string {
	return strings.ToLower(strings.TrimSpace(raw))
}

// adminEmailDomains อ่านโดเมนที่บังคับสำหรับบัญชีแอดมินจาก env
// คืน nil เมื่อไม่ได้ตั้งค่า = ไม่บังคับอะไร
func adminEmailDomains() []string {
	raw := strings.TrimSpace(os.Getenv("ADMIN_EMAIL_DOMAINS"))
	if raw == "" {
		return nil
	}

	var list []string
	for _, d := range strings.Split(raw, ",") {
		if d = strings.ToLower(strings.TrimSpace(d)); d != "" {
			list = append(list, d)
		}
	}
	return list
}

// emailDomain ดึงส่วนหลัง @ ออกมา คืนค่าว่างถ้ารูปแบบไม่ถูกต้อง
func emailDomain(email string) string {
	at := strings.LastIndex(email, "@")
	if at < 1 || at == len(email)-1 {
		return ""
	}
	return email[at+1:]
}

// ValidateEmailForRole ตรวจว่าอีเมลนี้ใช้กับบทบาทนี้ได้ไหม
//
// รับอีเมลที่ผ่าน NormalizeEmail มาแล้ว
func ValidateEmailForRole(email string, role models.UserRole) error {
	domain := emailDomain(email)
	if domain == "" || !strings.Contains(domain, ".") {
		return ErrEmailInvalid
	}

	// บังคับโดเมนเฉพาะบัญชีแอดมิน และเฉพาะเมื่อตั้งค่าไว้เท่านั้น
	if role != models.AdminRole {
		return nil
	}

	allowed := adminEmailDomains()
	if len(allowed) == 0 {
		return nil
	}

	for _, d := range allowed {
		if domain == d {
			return nil
		}
	}
	return fmt.Errorf("%w (ที่อนุญาต: %s)", ErrAdminEmailDomain, strings.Join(allowed, ", "))
}

