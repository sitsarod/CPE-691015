// กติกาความยาวรหัสผ่าน
//
// ทำไมต้องเช็คที่ชั้น service ทั้งที่ DTO มี binding:"min=8,max=72" อยู่แล้ว:
//
// binding tag ทำงานเฉพาะตอนที่ข้อมูลเข้ามาทาง HTTP handler เท่านั้น
// ถ้ามีใครเรียก CreateUser จากที่อื่น — เช่น seeder, สคริปต์ import ข้อมูล,
// หรือ endpoint ใหม่ที่ลืมใส่ binding — รหัสผ่านที่ไม่ผ่านเกณฑ์จะหลุดเข้าฐานได้เลย
//
// การเช็คซ้ำที่นี่ทำให้ "ทุกทางที่สร้างผู้ใช้" ผ่านด่านเดียวกันเสมอ
// ⚠️ สองเพดานนี้ "นับคนละหน่วย" โดยตั้งใจ อย่าทำให้เหมือนกัน
//
//	ขั้นต่ำ  นับเป็นตัวอักษร (rune) — เพราะเป็นกติกาที่สื่อกับผู้ใช้
//	เพดาน   นับเป็นไบต์ (byte)    — เพราะเป็นข้อจำกัดจริงของ bcrypt
//
// เคยเขียนผิดมาแล้ว: ใช้ len() ซึ่งนับไบต์กับ "ทั้งสองด้าน" ทำให้รหัสผ่าน
// ภาษาไทย 3 ตัวอักษร (กขค = 9 ไบต์) ผ่านด่าน "อย่างน้อย 8 ตัวอักษร" ไปได้
// ทั้งที่สั้นกว่าที่ประกาศไว้กับผู้ใช้มาก
const (
	// PasswordMinLength ความยาวขั้นต่ำ นับเป็น "ตัวอักษร"
	//
	// นับแบบเดียวกับที่ผู้ใช้เห็นบนหน้าจอ ไม่งั้นข้อความ "อย่างน้อย 8 ตัวอักษร"
	// จะไม่ตรงกับสิ่งที่ระบบบังคับจริง
	PasswordMinLength = 8

	// PasswordMaxLengthBytes เพดานของ bcrypt นับเป็น "ไบต์"
	//
	// bcrypt ตัดข้อมูลส่วนที่เกิน 72 ไบต์ทิ้งเงียบ ๆ ถ้าไม่กันไว้
	// รหัสผ่านที่ยาวกว่านี้จะถูกตัดโดยที่ผู้ใช้ไม่รู้ตัว และสองรหัสผ่านที่ต่างกัน
	// แต่ 72 ไบต์แรกเหมือนกันจะกลายเป็นรหัสเดียวกัน
	//
	// ภาษาไทย 1 ตัว = 3 ไบต์ จึงเท่ากับประมาณ 24 ตัวอักษร
	// ภาษาอังกฤษ 1 ตัว = 1 ไบต์ จึงเท่ากับ 72 ตัวอักษร
	PasswordMaxLengthBytes = 72
)

var (
	ErrPasswordTooShort = errors.New("รหัสผ่านต้องมีอย่างน้อย 8 ตัวอักษร")
	ErrPasswordTooLong  = errors.New("รหัสผ่านยาวเกินไป (ภาษาอังกฤษไม่เกิน 72 ตัว หรือภาษาไทยไม่เกิน 24 ตัว)")

	// ErrPasswordNoDigit กันรหัสผ่านที่เป็นตัวอักษรล้วน (เช่น "password") ซึ่งเดาง่าย
	// เพราะเดิมเช็คแค่ความยาว ตัวอักษรอะไรก็ได้ที่ยาวพอก็ผ่านด่านนี้ไปได้
	ErrPasswordNoDigit = errors.New("รหัสผ่านต้องมีตัวเลขอย่างน้อย 1 ตัว")
)

// SetPassword คือ "ทางเดียว" ที่ควรใช้เปลี่ยนรหัสผ่านของผู้ใช้
//
// รวมสามอย่างที่ต้องทำคู่กันเสมอไว้ในที่เดียว:
//
//	1. ตรวจความยาวตามกติกา
//	2. เข้ารหัสด้วย bcrypt
//	3. เดินเลขรุ่น token ขึ้นหนึ่ง เพื่อยกเลิก session เก่าทั้งหมด
//
// ⚠️ ข้อ 3 คือเหตุผลหลักที่ต้องมีฟังก์ชันนี้
//
// การเปลี่ยนรหัสผ่านโดยไม่ยกเลิก token เก่า เท่ากับบอกผู้ใช้ว่า "ปลอดภัยแล้ว"
// ทั้งที่คนที่ขโมยบัญชีไปยังอยู่ในระบบต่อได้จนกว่า token จะหมดอายุ
// ซึ่งอันตรายกว่าไม่มีปุ่มให้เปลี่ยนเสียอีก เพราะผู้ใช้จะเลิกระวังตัว
//
// รับรหัสผ่าน "ตัวจริง" ไม่ใช่ค่าที่ hash แล้ว โดยตั้งใจ — เพื่อไม่ให้มีใคร
// เผลอส่งรหัสผ่านดิบเข้าฐานเพราะคิดว่าอีกฝั่ง hash ให้แล้ว
func SetPassword(db *gorm.DB, user *models.User, plainPassword string) error {
	// ⚠️ ด่านนี้กันหายนะ ห้ามเอาออก
	//
	// db.Model(user) ใช้ค่า user.ID เป็นเงื่อนไข WHERE
	// ถ้า ID เป็น 0 (เช่นผู้เรียกเผลอส่ง struct เปล่ามา) GORM จะมองว่า
	// "ไม่มีเงื่อนไข" แล้วเขียนทับรหัสผ่านของผู้ใช้ "ทุกคน" ในระบบ
	// ทุกคนจะล็อกอินไม่ได้พร้อมกัน และกู้คืนไม่ได้เพราะ hash เดิมหายไปแล้ว
	if user == nil || user.ID == 0 {
		return errors.New("ไม่พบบัญชีผู้ใช้ที่จะตั้งรหัสผ่าน")
	}

	if err := ValidatePasswordStrength(plainPassword); err != nil {
		return err
	}

	hashed, err := bcrypt.GenerateFromPassword([]byte(plainPassword), bcrypt.DefaultCost)
	if err != nil {
		return errors.New("ไม่สามารถเข้ารหัสผ่านได้")
	}

	return db.Model(user).Updates(map[string]any{
		"password":      string(hashed),
		"token_version": gorm.Expr("token_version + 1"),
	}).Error
}

// ValidatePasswordStrength ตรวจความยาวรหัสผ่านก่อนนำไป hash
func ValidatePasswordStrength(password string) error {
	// ขั้นต่ำ — นับเป็นตัวอักษร ให้ตรงกับที่บอกผู้ใช้
	if utf8.RuneCountInString(password) < PasswordMinLength {
		return ErrPasswordTooShort
	}

	// เพดาน — นับเป็นไบต์ ตามข้อจำกัดจริงของ bcrypt
	if len(password) > PasswordMaxLengthBytes {
		return ErrPasswordTooLong
	}

	if !strings.ContainsAny(password, "0123456789") {
		return ErrPasswordNoDigit
	}
	return nil
}

