package models

import "time"

// AppSetting คือค่าตั้งค่าระดับองค์กรที่ต้องใช้ร่วมกันทุกเครื่อง
//
// ─── ทำไมต้องมีตารางนี้ ───
//
// ค่าอย่าง "อัตราส่วนโค้ช 1 คนต่อนักเรียนกี่คน" เป็นกฎทางธุรกิจของโรงเรียน
// ไม่ใช่ความชอบส่วนตัวของแต่ละเครื่อง แต่เดิมเก็บใน localStorage ของเบราว์เซอร์
// ผลคือแอดมินสองคนเห็นคำแนะนำจำนวนโค้ชไม่ตรงกัน แล้วเถียงกันว่าใครถูก
// และค่าหายทุกครั้งที่ล้างข้อมูลเบราว์เซอร์หรือเปลี่ยนเครื่อง
//
// ─── ทำไมเป็น key/value ไม่ใช่คอลัมน์ต่อค่า ───
//
// ค่าประเภทนี้เพิ่มทีละตัวเรื่อย ๆ ตามที่ทีมเจอ การเพิ่มคอลัมน์ทุกครั้ง
// ต้อง migrate ทุกครั้ง ส่วน key/value เพิ่มได้โดยไม่แตะสคีมา
//
// ⚠️ แต่ไม่เปิดเป็น API แบบ "เขียน key อะไรก็ได้"
// ทุกค่าต้องมี endpoint ของตัวเองที่ตรวจชนิดและช่วงที่รับได้
// (ดู settings_service.go) ไม่งั้นจะกลายเป็นถังขยะที่ไม่มีใครรู้ว่ามีอะไรอยู่
type AppSetting struct {
	Key   string `json:"key" gorm:"primaryKey;type:varchar(64)"`
	Value string `json:"value" gorm:"type:varchar(255);not null"`

	// ตอบได้ว่าใครเปลี่ยนค่ากฎธุรกิจนี้เมื่อไหร่ (users.id)
	UpdatedByUserID *uint     `json:"updated_by_user_id"`
	UpdatedAt       time.Time `json:"updated_at"`
}
