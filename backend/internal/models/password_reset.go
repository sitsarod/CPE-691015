package models

import (
	"time"

	"gorm.io/gorm"
)

// PasswordResetOTP คือรหัส OTP หนึ่งใบที่ออกให้ผู้ใช้เพื่อกู้รหัสผ่าน
//
// ─── ทำไมต้องเก็บเป็น hash ไม่ใช่ตัวเลขตรง ๆ ───
//
// ถ้าเก็บ "123456" ตรง ๆ แล้ววันหนึ่งฐานข้อมูลรั่ว คนที่ได้ไฟล์ไปจะเห็น OTP
// ของทุกคนที่กำลังกู้รหัสผ่านอยู่ แล้วยึดบัญชีได้ทันทีก่อนเจ้าตัวจะกรอก
//
// เก็บเป็น bcrypt hash แทน ทำให้ต่อให้ฐานรั่วก็ใช้ประโยชน์ไม่ได้ในเวลา 10 นาที
// ที่ OTP ยังไม่หมดอายุ
//
// ─── ทำไมต้องนับจำนวนครั้งที่กรอกผิด ───
//
// OTP มีแค่ 6 หลัก = ความเป็นไปได้ 1 ล้านแบบ ซึ่งเดารัว ๆ ไม่นานก็ถูก
// การจำกัดจำนวนครั้งทำให้โอกาสเดาถูกเหลือ 5 ใน 1,000,000 ต่อการขอหนึ่งครั้ง
type PasswordResetOTP struct {
	gorm.Model

	// UserID คือเจ้าของรหัสนี้ (users.id)
	UserID uint  `json:"user_id" gorm:"index;not null"`
	User   *User `json:"-" gorm:"foreignKey:UserID"`

	// CodeHash คือ bcrypt hash ของเลข 6 หลัก — ไม่เคยเก็บตัวเลขจริงลงฐาน
	CodeHash string `json:"-" gorm:"type:varchar(255);not null"`

	// ExpiresAt คือเวลาที่รหัสนี้หมดอายุ (สั้น ๆ เพื่อลดช่วงเวลาที่ถูกใช้ได้)
	ExpiresAt time.Time `json:"expires_at" gorm:"not null"`

	// Attempts คือจำนวนครั้งที่กรอกผิด เมื่อถึงเพดานจะใช้ใบนี้ไม่ได้อีก
	Attempts int `json:"attempts" gorm:"default:0"`

	// UsedAt บันทึกว่าใบนี้ถูกใช้ไปแล้วเมื่อไหร่ (nil = ยังไม่ถูกใช้)
	//
	// ใช้ได้ครั้งเดียวโดยตั้งใจ ถ้าใช้ซ้ำได้ คนที่แอบเห็นอีเมลจะย้อนมาใช้
	// รหัสเดิมได้อีกแม้เจ้าตัวจะตั้งรหัสผ่านใหม่ไปแล้ว
	UsedAt *time.Time `json:"used_at"`

	// หลักฐานประกอบสำหรับตรวจสอบย้อนหลัง — ไม่ส่งออกทาง API
	IPAddress string `json:"-" gorm:"type:varchar(45)"`
}
